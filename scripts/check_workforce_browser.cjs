// Exercise the real page and its public aggregate server functions.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const url=process.env.WORKFORCE_URL || 'http://127.0.0.1:8080/omraden/arbetsmarknad/arbetskraft';
  await page.goto(url,{waitUntil:'networkidle',timeout:120000});
  await page.getByRole('heading',{name:'Hur ser arbetskraften ut?',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Vilka grupper står utanför arbetskraften?',exact:true}).waitFor();
  assert.equal(await page.getByRole('alert').count(),0,'Initial data load failed');
  assert.ok(await page.locator('#utveckling .recharts-line').count()>0,'Workforce time series is empty');
  assert.equal(await page.locator('#alder .recharts-bar').count(),2,'Age pyramid must show both sexes');
  await page.getByLabel('Geografi',{exact:true}).selectOption('2580');
  await page.waitForLoadState('networkidle');
  assert.match(page.url(),/geo=2580/);
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('birth-month');
  await page.waitForLoadState('networkidle');
  assert.equal(await page.getByRole('alert').count(),0,'Birth region view failed');
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('education-month');
  await page.waitForLoadState('networkidle');
  await page.getByLabel('Mått',{exact:true}).selectOption({label:'arbetskraftsdeltagande'});
  await page.waitForLoadState('networkidle');
  assert.equal(await page.getByRole('alert').count(),0,'Education participation failed');
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('occupation-year');
  await page.waitForLoadState('networkidle');
  assert.match(await page.locator('main').innerText(),/Här visas Norrbottens län/);
  assert.equal(await page.getByRole('alert').count(),0,'Occupation view failed');
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('industry-age');
  await page.waitForLoadState('networkidle');
  assert.match(await page.locator('main').innerText(),/Här visas Riket/);
  assert.equal(await page.getByRole('alert').count(),0,'National industry view failed');
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('retirement-education');
  await page.waitForLoadState('networkidle');
  await page.getByLabel('Utbildningsindelning',{exact:true}).first().selectOption('inriktning');
  await page.waitForLoadState('networkidle');
  assert.equal(await page.getByRole('alert').count(),0,'RMI U4 view failed');
  await page.getByLabel('Underlag och uppdelning',{exact:true}).selectOption('status-month');
  await page.waitForLoadState('networkidle');
  await page.locator('#utveckling').getByRole('button',{name:'Visa datatabell',exact:true}).click();
  assert.ok(await page.locator('#utveckling tbody tr').count()>=80);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#utveckling').getByRole('button',{name:'Ladda ned CSV',exact:true}).click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'arbetskraft.csv');
  await page.screenshot({path:'/tmp/workforce-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  const overflow = await page.evaluate(()=>({width:window.innerWidth,scroll:document.documentElement.scrollWidth,elements:[...document.querySelectorAll('main *')].filter(e=>e.getBoundingClientRect().right>window.innerWidth+1).slice(0,12).map(e=>({tag:e.tagName,class:e.className,text:e.textContent.slice(0,80)}))}));
  assert.ok(overflow.scroll<=overflow.width+1, 'Horizontal overflow on mobile: '+JSON.stringify(overflow));
  await page.screenshot({path:'/tmp/workforce-mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'Browser errors');
  console.log('Workforce desktop/mobile, source selection, missing geography, table and CSV verified.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
